#!/bin/sh
# Installs or upgrades Self-Hosted on a Linux server with Docker.
#
# The panel (API, web, PostgreSQL, Redis, Traefik):
#   curl -fsSL https://raw.githubusercontent.com/KROWIEL/self-hosted/main/deploy/install.sh | sudo sh
#
# An additional server that only runs apps (Traefik; the node agent is then
# added from the panel):
#   curl -fsSL https://raw.githubusercontent.com/KROWIEL/self-hosted/main/deploy/install.sh | sudo sh -s node
#
# Re-running it upgrades to the latest release and keeps your settings.
#
# Env (all optional; you are asked for the domain and email when missing):
#   PANEL_DOMAIN        domain the panel is served on, e.g. panel.example.com
#   ACME_EMAIL          email for Let's Encrypt certificates
#   ADMIN_EMAIL         first administrator login       (default: ACME_EMAIL)
#   SELFHOSTED_VERSION  release tag to install           (default: latest)
#   INSTALL_DIR         where the stack lives            (default: /opt/selfhosted)
set -eu

REPO="KROWIEL/self-hosted"
MODE="${1:-panel}"
INSTALL_DIR="${INSTALL_DIR:-/opt/selfhosted}"
CERTS_DIR=/var/lib/selfhosted-agent/traefik

say()  { printf '\033[1;36m>>\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

case "$MODE" in panel|node) ;; *) fail "unknown mode '$MODE' (use: panel or node)" ;; esac
[ "$(uname -s)" = "Linux" ] || fail "this installer supports Linux only"
[ "$(id -u)" = "0" ] || fail "run as root (sudo sh install.sh)"
command -v curl >/dev/null 2>&1 || fail "curl is required"
command -v openssl >/dev/null 2>&1 || fail "openssl is required"

if ! command -v docker >/dev/null 2>&1; then
  say "Docker not found, installing it with the official script (get.docker.com)"
  curl -fsSL https://get.docker.com | sh
fi
docker compose version >/dev/null 2>&1 || fail "the Docker Compose plugin is required (docker compose)"

# Ask on the terminal even when the script itself arrives through a pipe.
ask() {
  printf '%s' "$1" > /dev/tty
  read -r answer < /dev/tty
  printf '%s' "$answer"
}

if [ -z "${SELFHOSTED_VERSION:-}" ]; then
  latest="$(curl -fsSLI -o /dev/null -w '%{url_effective}' "https://github.com/$REPO/releases/latest")"
  SELFHOSTED_VERSION="${latest##*/}"
  case "$SELFHOSTED_VERSION" in v*) ;; *) fail "could not find the latest release of $REPO" ;; esac
fi

download() {
  curl -fsSL "https://raw.githubusercontent.com/$REPO/$SELFHOSTED_VERSION/deploy/$1" -o "$1"
}

say "Installing Self-Hosted $SELFHOSTED_VERSION ($MODE) into $INSTALL_DIR"
mkdir -p "$INSTALL_DIR" "$CERTS_DIR/certs" "$CERTS_DIR/dynamic"
cd "$INSTALL_DIR"
download traefik.yml
if [ "$MODE" = "panel" ]; then download docker-compose.yml; fi

fresh=0
if [ ! -f .env ]; then
  fresh=1
  if [ "$MODE" = "panel" ]; then
    PANEL_DOMAIN="${PANEL_DOMAIN:-$(ask 'Panel domain (DNS must point to this server, e.g. panel.example.com): ')}"
    [ -n "$PANEL_DOMAIN" ] || fail "a panel domain is required"
  fi
  ACME_EMAIL="${ACME_EMAIL:-$(ask "Email for Let's Encrypt certificates: ")}"
  [ -n "$ACME_EMAIL" ] || fail "an email is required"

  umask 077
  if [ "$MODE" = "node" ]; then
    cat > .env <<EOF
# Generated by install.sh. Keep this file private.
COMPOSE_FILE=traefik.yml
COMPOSE_PROJECT_NAME=selfhosted
SELFHOSTED_VERSION=$SELFHOSTED_VERSION
ACME_EMAIL=$ACME_EMAIL
# CLOUDFLARE_DNS_API_TOKEN=
EOF
  else
    ADMIN_EMAIL="${ADMIN_EMAIL:-$ACME_EMAIL}"
    # Satisfies the panel's password policy: 12+ chars, upper, lower, 3 digits, special.
    ADMIN_PASSWORD="$(openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | head -c 16)-Q7k2x9"
    cat > .env <<EOF
# Generated by install.sh. Keep this file private.
SELFHOSTED_VERSION=$SELFHOSTED_VERSION
PANEL_DOMAIN=$PANEL_DOMAIN
ACME_EMAIL=$ACME_EMAIL

POSTGRES_PASSWORD=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
JWT_REFRESH_SECRET=$(openssl rand -base64 48 | tr -d '\n')
WEBHOOK_SECRET=$(openssl rand -base64 32 | tr -d '\n')
ENCRYPTION_KEY=$(openssl rand -base64 32 | tr -d '\n')

# First administrator, created on the first start only.
ADMIN_EMAIL=$ADMIN_EMAIL
ADMIN_PASSWORD=$ADMIN_PASSWORD

# Public sign-up stays off; invite people from the panel instead.
ALLOW_OPEN_REGISTRATION=0

# Wildcard certificates through DNS-01 (optional, see docs/INSTALL.md).
# ACME_WILDCARD_CERTS=1
# CLOUDFLARE_DNS_API_TOKEN=
EOF
  fi
  umask 022
else
  say "Keeping the existing settings in $INSTALL_DIR/.env"
  if grep -q '^SELFHOSTED_VERSION=' .env; then
    sed -i "s/^SELFHOSTED_VERSION=.*/SELFHOSTED_VERSION=$SELFHOSTED_VERSION/" .env
  else
    printf 'SELFHOSTED_VERSION=%s\n' "$SELFHOSTED_VERSION" >> .env
  fi
fi

say "Pulling images"
docker compose pull
say "Starting"
docker compose up -d --remove-orphans

echo
if [ "$MODE" = "node" ]; then
  say "Done. Traefik is serving ports 80 and 443 on this server."
  echo "   Next: in the panel open Nodes -> Add remote node, enter this server's"
  echo "   public IP or domain and run the command it shows here."
  exit 0
fi

PANEL_DOMAIN="$(grep '^PANEL_DOMAIN=' .env | cut -d= -f2-)"
say "Done. Open https://$PANEL_DOMAIN"
if [ "$fresh" = "1" ]; then
  echo "   Administrator: $ADMIN_EMAIL"
  echo "   Password:      $ADMIN_PASSWORD"
  echo "   (also stored in $INSTALL_DIR/.env; change it after the first sign-in)"
fi
echo
echo "   Next: in the panel open Nodes -> Add remote node, enter this server's"
echo "   public IP or domain and run the command it shows here. The node agent"
echo "   is what builds and runs your apps."
